package com.maddyhome.idea.vim.largefile

import com.maddyhome.idea.vim.largefile.GotoDeclarationVisibleEditorsTest.Companion.largeJavaClass
import org.junit.jupiter.api.AfterAll
import org.junit.jupiter.api.Test

/**
 * Measures Go to Declaration into a large file while other large files are visible in splits (VIM-4342)
 *
 * Opening the declaration selects another editor. IdeaVim 2.39 then refreshed the search count in every visible
 * editor, searching each of them completely when the last search pattern doesn't match there. So the time should grow
 * with the number of visible large editors in 2.39, and not at all in 2.38.
 */
class GotoDeclarationVisibleEditorsTest : IdeaVimLargeFileTestBase() {

  private val results = linkedMapOf<Int, List<Long>>()

  // Go to Declaration is Ctrl+B outside macOS, which IdeaVim handles as <C-B> (scroll back) unless told otherwise
  override fun ideaVimRcContent(): String = "sethandler <C-B> a:ide"

  override fun createProjectFiles() {
    createJavaModule()
    (1..LARGE_FILES).forEach { createFile("src/${largeName(it)}", largeJavaClass(largeClass(it))) }
    createFile(
      CALLER,
      """
      |public class Caller {
      |  // $PATTERN
      |  public void run(Big1 big) {
      |    big.method$TARGET_METHOD(1);
      |  }
      |}
      |""".trimMargin()
    )
  }

  @Test
  fun `go to declaration with other large files visible`() {
    openFile(CALLER)
    // Only matches in Caller.java, so counting it means searching all of every large file
    typeVim("/$PATTERN\n")

    for (otherLargeEditors in OTHER_LARGE_EDITORS) {
      showLargeFilesNextToCaller(otherLargeEditors)
      val samples = mutableListOf<Long>()
      repeat(WARMUP + ITERATIONS) { i ->
        val elapsed = gotoDeclarationFromCaller()
        if (i >= WARMUP) samples += elapsed
      }
      results[otherLargeEditors] = samples
      publishMetric("gotoDeclaration.otherLargeEditors$otherLargeEditors", median(samples))
      println("[$otherLargeEditors other large editors visible] ${minMedianMax(samples)}")
    }
  }

  @AfterAll
  fun printReport() {
    println()
    println("Go to Declaration into $LARGE_LINES-line Big1.java (ms, min/median/max)")
    results.forEach { (others, samples) ->
      println("%-36s %s".format("$others other large editors visible", minMedianMax(samples)))
    }
  }

  /** Leaves Caller.java in the current window, with [count] other large files each in a split of its own */
  private fun showLargeFilesNextToCaller(count: Int) {
    openFile(CALLER)
    typeVim(":only\n")
    (2 until 2 + count).forEach { largeFile ->
      typeVim(":vsplit\n")
      openFile("src/${largeName(largeFile)}")
      focusEditor(CALLER_NAME)
    }
  }

  private fun gotoDeclarationFromCaller(): Long {
    openFile(CALLER)
    typeVim("${CALL_LINE + 1}G^f.l")
    check(waitUntil { selectedEditorState() == EditorState(CALLER_NAME, CALL_LINE) }) {
      "Caret did not move to the call. Actual: ${selectedEditorState()}"
    }
    return measureNavigation(EditorState(largeName(1), methodLine(TARGET_METHOD))) { gotoDeclaration() }
  }

  private fun minMedianMax(values: List<Long>): String = "${values.min()}/${median(values)}/${values.max()}"

  private fun median(values: List<Long>): Long = values.sorted()[values.size / 2]

  companion object {
    private const val CALLER_NAME = "Caller.java"
    private const val CALLER = "src/$CALLER_NAME"
    private const val CALL_LINE = 3
    private const val PATTERN = "needleInCaller"

    private const val LARGE_FILES = 4
    private const val LARGE_METHODS = 15_000
    private const val LARGE_LINES = LARGE_METHODS * 5 + 2
    private const val TARGET_METHOD = 14_500

    private val OTHER_LARGE_EDITORS = listOf(0, 1, 3)

    private const val WARMUP = 1
    private const val ITERATIONS = 3

    private fun largeClass(n: Int) = "Big$n"
    private fun largeName(n: Int) = "${largeClass(n)}.java"

    /** 0-based line of `methodN` in a file generated by [largeJavaClass] */
    private fun methodLine(n: Int) = 1 + n * 5

    private fun largeJavaClass(name: String): String = buildString {
      append("public class $name {\n")
      repeat(LARGE_METHODS) { i ->
        append("  public int method$i(int x) {\n")
        append("    int value = x + $i;\n")
        append("    return value * 2;\n")
        append("  }\n")
        append("\n")
      }
      append("}\n")
    }
  }
}
