/**
 * Base class for IdeaVim tests that run a full IDE (monolith, not split mode) against large files.
 *
 * Files are generated by [createProjectFiles] before the IDE starts, so they are indexed by the time tests run.
 *
 * Timings are printed rather than asserted: they depend too much on the machine to make stable thresholds. On
 * TeamCity, the medians are published with [publishMetric], to follow them over time.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
abstract class IdeaVimLargeFileTestBase {

  private lateinit var bgRun: BackgroundRun
  private lateinit var context: IDETestContext
  protected lateinit var driver: Driver
  protected lateinit var projectDir: Path

  @BeforeAll
  fun launchIde() {
    projectDir = kotlin.io.path.createTempDirectory("ideavim-large-file-test")
    createProjectFiles()

    context = Starter.newContext(
      this::class.simpleName ?: "large-file-test",
      TestCase(ide, LocalProjectInfo(projectDir)).useRelease("2026.1")
    )

    resolvePluginPath()?.let { PluginConfigurator(context).installPluginFromPath(it) }
    context.useTestIdeaVimRc()

    // The default 10 minutes is not enough once searches in large files take seconds each
    bgRun = context.runIdeWithDriver(runTimeout = 30.minutes)
    driver = bgRun.driver

    driver.withContext { waitForIndicators(10.minutes) }
  }

  @AfterAll
  fun closeIde() {
    if (::bgRun.isInitialized) bgRun.closeIdeAndWait()
    if (::context.isInitialized) reportFreezes()
  }

  /** The IDE to run the tests in */
  protected open val ide: IdeInfo = IDEA_ULTIMATE

  /** Writes the files the tests need into [projectDir]. Called before the IDE starts. */
  protected abstract fun createProjectFiles()

  /** Content of the ideavimrc the launched IDE will use */
  protected open fun ideaVimRcContent(): String = ""

  /**
   * Points the launched IDE at a test-owned ideavimrc, so the developer's real `~/.ideavimrc` doesn't change the
   * results.
   *
   * `IDEA_VIM_CUSTOM_VIMRC` only exists since 2.43, so `user.home` is redirected as well. That keeps the comparison
   * fair when running against an older release via `-PideavimPluginZip`.
   */
  private fun IDETestContext.useTestIdeaVimRc() {
    val home = kotlin.io.path.createTempDirectory("ideavim-large-file-home")
    val vimrc = home.resolve(".ideavimrc")
    vimrc.writeText(ideaVimRcContent())
    applyVMOptionsPatch {
      withEnv("IDEA_VIM_CUSTOM_VIMRC", vimrc.absolutePathString())
      addSystemProperty("user.home", home)
    }
  }

  /**
   * Makes [projectDir] a Java module with `src` as source root, so Go to Declaration works for Java files without a JDK
   */
  protected fun createJavaModule() {
    projectDir.resolve(".idea").createDirectories().resolve("modules.xml").writeText(
      """
      |<?xml version="1.0" encoding="UTF-8"?>
      |<project version="4">
      |  <component name="ProjectModuleManager">
      |    <modules>
      |      <module fileurl="file://${'$'}PROJECT_DIR${'$'}/large.iml" filepath="${'$'}PROJECT_DIR${'$'}/large.iml" />
      |    </modules>
      |  </component>
      |</project>
      """.trimMargin()
    )
    projectDir.resolve("large.iml").writeText(
      """
      |<?xml version="1.0" encoding="UTF-8"?>
      |<module type="JAVA_MODULE" version="4">
      |  <component name="NewModuleRootManager" inherit-compiler-output="true">
      |    <exclude-output />
      |    <content url="file://${'$'}MODULE_DIR${'$'}">
      |      <sourceFolder url="file://${'$'}MODULE_DIR${'$'}/src" isTestSource="false" />
      |    </content>
      |    <orderEntry type="sourceFolder" forTests="false" />
      |  </component>
      |</module>
      """.trimMargin()
    )
  }

  /**
   * Prints the freeze thread dumps the IDE's performance watcher wrote during the run. A freeze means the EDT was
   * blocked, which is exactly what makes searching feel slow.
   */
  private fun reportFreezes() {
    val freezes = Files.walk(context.paths.testHome).use { paths ->
      paths.filter { it.isDirectory() && it.name.startsWith("threadDumps-freeze") }.toList()
    }
    publishMetric("${this::class.simpleName}.freezes", freezes.size.toLong())
    if (freezes.isEmpty()) {
      println("No UI freezes recorded")
    } else {
      println("UI freezes recorded (${freezes.size}):")
      freezes.forEach { println("  $it") }
    }
  }

  /**
   * Publishes [value] as the TeamCity build statistic `ideavim.largeFile.<key>`, shown as a trend on the project's
   * Statistics tab
   *
   * The service messages are written to a file that the build prints after the tests, rather than to the test output,
   * which Gradle indents. Does nothing when not run through Gradle.
   */
  protected fun publishMetric(key: String, value: Long) {
    val dir = System.getProperty("ideavim.metrics.dir") ?: return
    Path(dir).createDirectories().resolve("${this::class.simpleName}.txt").writeText(
      "##teamcity[buildStatisticValue key='ideavim.largeFile.$key' value='$value']\n",
      Charsets.UTF_8,
      StandardOpenOption.CREATE,
      StandardOpenOption.APPEND,
    )
  }

  // ── File helpers ────────────────────────────────────────────

  /** Creates a file in the project. Returns relative path for [openFile]. */
  protected fun createFile(relativePath: String, content: String): String {
    val file = projectDir.resolve(relativePath)
    file.parent.createDirectories()
    file.writeText(content)
    return relativePath
  }

  // ── IDE interaction helpers ─────────────────────────────────

  /** Opens a file in the current editor window and waits until IdeaVim handles keys in it. */
  protected fun openFile(relativePath: String) {
    driver.withContext { openFile(relativePath, waitForCodeAnalysis = false) }
    val fileName = Path(relativePath).name
    val ready = waitUntil(timeoutMs = 30_000, pollMs = 500) {
      try {
        typeVim("gg", fileName)
        selectedEditorState() == EditorState(fileName, 0)
      } catch (_: Exception) {
        false
      }
    }
    check(ready) { "Editor for '$relativePath' did not become ready, or IdeaVim did not handle keys in it" }
  }

  /**
   * Types vim keys in the editor showing [fileName], the selected editor by default.
   *
   * Editors are addressed by file because `codeEditor()` fails as soon as more than one editor is visible. Splits need
   * to show different files for this to work.
   */
  protected fun typeVim(keys: String, fileName: String = selectedFileName()) {
    driver.withContext {
      requestFocusFromIde(singleProject())
      ideFrame {
        codeEditorForFile(fileName).apply {
          waitFound()
          component.requestFocus()
          keyboard { typeText(keys) }
        }
      }
    }
  }

  /** Focuses the editor showing [fileName], which also makes its window the current one. */
  protected fun focusEditor(fileName: String) {
    driver.withContext {
      requestFocusFromIde(singleProject())
      ideFrame { codeEditorForFile(fileName).apply { waitFound(); click() } }
    }
    check(waitUntil { selectedEditorState()?.fileName == fileName }) { "Could not focus the editor for $fileName" }
  }

  // ── Editor state helpers ────────────────────────────────────

  protected data class EditorState(val fileName: String, val caretLine: Int)

  /**
   * Reads the selected editor's file and 0-based caret line.
   *
   * Runs on the EDT, so the call can't complete until the EDT is free. Polling this after a key press measures the
   * time until the IDE has finished handling it, not just the time until the caret moved.
   */
  protected fun selectedEditorState(): EditorState? {
    return driver.withContext(OnDispatcher.EDT) {
      val editor = service<FileEditorManager>(singleProject()).getSelectedTextEditor() ?: return@withContext null
      EditorState(editor.getVirtualFile().getName(), editor.getCaretModel().getLogicalPosition().getLine())
    }
  }

  private fun selectedFileName(): String = checkNotNull(selectedEditorState()) { "No editor is selected" }.fileName

  protected fun waitUntil(timeoutMs: Long = 5000, pollMs: Long = 200, check: () -> Boolean): Boolean {
    val deadline = System.currentTimeMillis() + timeoutMs
    while (System.currentTimeMillis() < deadline) {
      if (check()) return true
      Thread.sleep(pollMs)
    }
    return false
  }

  /** Milliseconds until the caret moved, and until the search count was shown, or null if no count was expected */
  data class SearchTiming(val caretMs: Long, val countMs: Long?)

  /**
   * Sends [keys] to the selected editor and measures how long until its caret is on [caretLine] (0-based), and then
   * until the output panel shows [searchCount].
   *
   * The clock starts right before the keys are sent, after the editor component has been looked up, so the driver's
   * own overhead isn't part of the result. Type everything that shouldn't be measured, such as the pattern of a
   * search, beforehand with [typeVim].
   */
  protected fun measureSearch(
    caretLine: Int,
    searchCount: String? = null,
    timeoutMs: Long = 30_000,
    keys: RemoteKeyboard.() -> Unit,
  ): SearchTiming {
    val fileName = selectedFileName()
    val start = pressKeys(fileName, keys)
    val caretMs = waitForSelectedEditor(EditorState(fileName, caretLine), start, timeoutMs)
    if (searchCount == null) return SearchTiming(caretMs, null)

    var count = ""
    val counted = waitUntil(timeoutMs = timeoutMs, pollMs = 5) {
      count = searchCountText()
      count == searchCount
    }
    val countMs = millisSince(start)
    check(counted) { "Expected search count $searchCount within ${timeoutMs}ms. Actual: '$count'" }
    return SearchTiming(caretMs, countMs)
  }

  /**
   * Sends [keys] to the selected editor and returns the milliseconds until [target] is the selected editor, with the
   * caret on the expected line. Use this to measure navigation to another file.
   */
  protected fun measureNavigation(target: EditorState, timeoutMs: Long = 30_000, keys: RemoteKeyboard.() -> Unit): Long {
    val start = pressKeys(selectedFileName(), keys)
    return waitForSelectedEditor(target, start, timeoutMs)
  }

  /** Presses Go to Declaration: Ctrl+B in the default keymap, Cmd+B in the macOS one */
  protected fun RemoteKeyboard.gotoDeclaration() {
    val modifier = if (System.getProperty("os.name").lowercase().contains("mac")) KeyEvent.VK_META else KeyEvent.VK_CONTROL
    pressing(modifier) { key(KeyEvent.VK_B) }
  }

  private fun waitForSelectedEditor(target: EditorState, start: Long, timeoutMs: Long): Long {
    var state: EditorState? = null
    val reached = waitUntil(timeoutMs = timeoutMs, pollMs = 5) {
      state = selectedEditorState()
      state == target
    }
    val elapsedMs = millisSince(start)
    check(reached) { "Expected $target within ${timeoutMs}ms. Actual: $state" }
    return elapsedMs
  }

  /** Sends [keys] to the editor showing [fileName], and returns [System.nanoTime] from right before they were sent */
  private fun pressKeys(fileName: String, keys: RemoteKeyboard.() -> Unit): Long {
    var start = 0L
    driver.withContext {
      ideFrame {
        codeEditorForFile(fileName).apply {
          waitFound()
          keyboard {
            start = System.nanoTime()
            keys()
          }
        }
      }
    }
    return start
  }

  private fun millisSince(nanoTime: Long): Long = (System.nanoTime() - nanoTime) / 1_000_000

  /**
   * Reads the search count shown in IdeaVim's output panel, e.g. `[2/3]`, or `[?/??]` while it's still counting.
   * Returns an empty string if no count is shown.
   */
  protected fun searchCountText(): String {
    var result = ""
    driver.withContext {
      ideFrame {
        val panel = x("//div[@class='OutputPanel']")
        if (panel.present()) {
          result = panel.getAllTexts().map { it.text.trim() }.firstOrNull { SEARCH_COUNT.matches(it) } ?: ""
        }
      }
    }
    return result
  }

  companion object {
    private val SEARCH_COUNT = Regex("""\[[^/\]]+/[^/\]]+]""")

    // Inlined IdeInfo for IntelliJ IDEA Ultimate. Avoids the IdeProductProvider/IdeInfo.IdeaUltimate
    // API that varies across IntelliJ build numbers (renamed/removed in 262 EAP).
    private val IDEA_ULTIMATE = IdeInfo(
      productCode = "IU",
      platformPrefix = "idea",
      executableFileName = "idea",
      fullName = "IDEA",
      qodanaProductCode = "QDJVM",
    )

    /** The IdeaVim plugin to install, or null to run without IdeaVim (`-PideavimPluginZip=none`) */
    fun resolvePluginPath(): Path? {
      val pathStr = System.getProperty("ideavim.plugin.path")
        ?: error(
          "System property 'ideavim.plugin.path' is not set. " +
            "Run via: ./gradlew :tests:large-file-tests:testLargeFiles"
        )
      return if (pathStr == NO_PLUGIN) null else Path(pathStr)
    }

    private const val NO_PLUGIN = "none"
  }
}
